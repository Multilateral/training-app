export const getExerciseTrackingType = (exercise) => {
  if (!exercise) return 'weight_reps';

  // 1. Explicit tracking type field has highest precedence
  const explicit = exercise.tracking_type || exercise.trackingType;
  if (explicit === 'time' || explicit === 'duration') return 'time';
  if (explicit === 'weight_reps') return 'weight_reps';
  if (explicit === 'reps' || explicit === 'bodyweight') return 'reps';
  if (explicit === 'manual') return 'manual';

  const n = (exercise.name || '').toLowerCase();
  const c = (exercise.category || '').toLowerCase();
  const eq = (exercise.equipment || '').toLowerCase();
  const m = (exercise.mechanics || '').toLowerCase();

  // 2. Tempo-regulated repetition exercises (Cat-Cow, Bird-Dog, McGill Curl-up, etc.)
  if (
    exercise.seconds_per_rep ||
    exercise.hold_seconds_per_rep ||
    n.includes('cat-cow') ||
    n.includes('cat cow') ||
    n.includes('bird-dog') ||
    n.includes('mcgill')
  ) {
    return 'reps';
  }

  // 0. Manual / Hours log (Collective Sports, sport matches, outdoor activities)
  if (
    c.includes('collective sports') ||
    c.includes('sports') ||
    m.includes('manual') ||
    n === 'tennis' ||
    n === 'soccer' ||
    n === 'football' ||
    n === 'basketball' ||
    n === 'volleyball' ||
    n === 'badminton' ||
    n === 'rugby' ||
    n === 'cricket' ||
    n === 'baseball' ||
    n === 'water polo' ||
    n === 'handball' ||
    n === 'hockey'
  ) {
    return 'manual';
  }

  // 1. Time-related (pure holds, isometrics, static planks, yoga poses)
  if (
    n.includes('hold') ||
    n.includes('plank') ||
    n.includes('wall sit') ||
    n.includes('l-sit') ||
    n.includes('hollow') ||
    n.includes('spanish squat') ||
    n.includes('balance') ||
    n.includes('deadbug') ||
    n.includes('alphabet') ||
    c === 'yoga' ||
    n.includes('pose') ||
    n.includes('dog') ||
    n.includes('chaturanga') ||
    n.includes('warrior') ||
    n.includes('thread the needle') ||
    m.includes('isometric') ||
    m.includes('static')
  ) {
    return 'time';
  }

  // 2. Weight + Rep related (barbell, dumbbell, kettlebell, loaded resistance)
  if (
    eq.includes('dumbbell') ||
    eq.includes('barbell') ||
    eq === 'kettlebell' ||
    n.includes('bench press') ||
    n.includes('deadlift') ||
    (n.includes('squat') && !n.includes('pistol') && !n.includes('jump')) ||
    (n.includes('curl') && !n.includes('nordic') && !n.includes('mcgill')) ||
    n.includes('overhead press') ||
    n.includes('clean') ||
    n.includes('snatch') ||
    n.includes('kettlebell') ||
    (n.includes('row') && !n.includes('trx') && !n.includes('inverted')) ||
    n.includes('farmer') ||
    n.includes('suitcase') ||
    n.includes('halo')
  ) {
    return 'weight_reps';
  }

  // 3. Rep-related / Bodyweight (pull-ups, push-ups, dips, box jumps, TRX, calisthenics)
  return 'bodyweight';
};
